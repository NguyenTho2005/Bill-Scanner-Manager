import 'package:bill_tracker/features/budget/domain/entities/budget.dart';
import 'package:equatable/equatable.dart';

/// Role of a user within a household.
enum HouseholdRole {
  /// Household creator/admin who can invite or remove members.
  owner,

  /// Standard household member who can view/create shared budgets and shared expenses.
  member,
}

/// Member record inside a household.
class HouseholdMember extends Equatable {
  /// Creates a [HouseholdMember].
  const HouseholdMember({
    required this.householdId,
    required this.userId,
    required this.role,
    required this.joinedAt,
    this.displayName,
  });

  /// Parent household identifier.
  final String householdId;

  /// Member's authenticated user ID.
  final String userId;

  /// Role within the household.
  final HouseholdRole role;

  /// Display name shown next to shared expenses.
  final String? displayName;

  /// Timestamp when the member joined.
  final DateTime joinedAt;

  /// Best human-readable label for UI attribution.
  String get effectiveName =>
      (displayName != null && displayName!.trim().isNotEmpty)
          ? displayName!.trim()
          : userId;

  @override
  List<Object?> get props => [
        householdId,
        userId,
        role,
        displayName,
        joinedAt,
      ];
}

/// A shared household group.
class Household extends Equatable {
  /// Creates a [Household].
  const Household({
    required this.id,
    required this.name,
    required this.createdBy,
    required this.createdAt,
    this.members = const [],
  });

  /// Household identifier.
  final String id;

  /// Display name (e.g. "Gia đình Minh - Lan").
  final String name;

  /// Owner user ID.
  final String createdBy;

  /// Creation timestamp.
  final DateTime createdAt;

  /// Active household members.
  final List<HouseholdMember> members;

  @override
  List<Object?> get props => [id, name, createdBy, createdAt, members];
}

/// Invitation code and deep link generated by a household owner.
class HouseholdInvite extends Equatable {
  /// Creates a [HouseholdInvite].
  const HouseholdInvite({
    required this.id,
    required this.householdId,
    required this.code,
    required this.inviteLink,
    required this.expiresAt,
    required this.createdAt,
  });

  /// Invite identifier.
  final String id;

  /// Target household identifier.
  final String householdId;

  /// Short invite code (e.g. "BT-AB12CD").
  final String code;

  /// Deep link URL (`billtracker://household/join?code=...`).
  final String inviteLink;

  /// Expiration timestamp.
  final DateTime expiresAt;

  /// Creation timestamp.
  final DateTime createdAt;

  @override
  List<Object?> get props => [
        id,
        householdId,
        code,
        inviteLink,
        expiresAt,
        createdAt,
      ];
}

/// Shared expense entry attributed to its creator for household transparency.
class SharedExpenseItem extends Equatable {
  /// Creates a [SharedExpenseItem].
  const SharedExpenseItem({
    required this.id,
    required this.householdId,
    required this.categoryId,
    required this.amount,
    required this.currency,
    required this.occurredAt,
    required this.createdByUserId,
    required this.createdByName,
    this.type = 'expense',
    this.merchant,
    this.note,
    this.isShared = true,
  });

  /// Transaction identifier.
  final String id;

  /// Household identifier.
  final String householdId;

  /// Category identifier.
  final String categoryId;

  /// 'expense' or 'income'.
  final String type;

  /// Amount in VND.
  final double amount;

  /// Currency code.
  final String currency;

  /// Optional merchant name.
  final String? merchant;

  /// Optional note.
  final String? note;

  /// Occurrence timestamp.
  final DateTime occurredAt;

  /// Explicit sharing flag (must be true for household visibility).
  final bool isShared;

  /// Authenticated creator user ID.
  final String createdByUserId;

  /// Creator display name shown in UI ("ai chi tiêu gì").
  final String createdByName;

  @override
  List<Object?> get props => [
        id,
        householdId,
        categoryId,
        type,
        amount,
        currency,
        merchant,
        note,
        occurredAt,
        isShared,
        createdByUserId,
        createdByName,
      ];
}

/// Shared budget with aggregated spend and attributed recent transactions.
class SharedBudgetSummary extends Equatable {
  /// Creates a [SharedBudgetSummary].
  const SharedBudgetSummary({
    required this.budget,
    required this.spentAmount,
    required this.progressRatio,
    this.recentTransactions = const [],
  });

  /// Underlying shared [Budget] (with non-null `householdId`).
  final Budget budget;

  /// Confirmed shared spending within the budget period.
  final double spentAmount;

  /// Ratio `spentAmount / budget.amountLimit`.
  final double progressRatio;

  /// Recent shared transactions contributing to this budget.
  final List<SharedExpenseItem> recentTransactions;

  /// Remaining amount before hitting the budget limit.
  double get remainingAmount => budget.amountLimit - spentAmount;

  @override
  List<Object?> get props => [
        budget,
        spentAmount,
        progressRatio,
        recentTransactions,
      ];
}
